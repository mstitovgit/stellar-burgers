const mockError: Error = {
  name: 'MockError',
  message: 'MockErrorMessage'
};

describe('IngredientsSlice: Тест fetchIngredients', () => {
  test('fetchIngredients.pending — должен установить loading=true и сбросить error', () => {
    const stateWithError = {
      ...initialState,
      error: 'Old error message'
    };

    const newState = ingredientsReducer(
      stateWithError,
      fetchIngredients.pending('', undefined)
    );

    expect(newState.loading).toBe(true);
    expect(newState.error).toBe(null);
    expect(newState.data).toEqual([]);
  });

  test('fetchIngredients.fulfilled — должен установить loading=false и обновить data', () => {
    const stateWithRequest = {
      ...initialState,
      loading: true
    };

    const newState = ingredientsReducer(
      stateWithRequest,
      fetchIngredients.fulfilled(mockData, '', undefined)
    );

    expect(newState.loading).toBe(false);
    expect(newState.error).toBe(null);
    expect(newState.data).toEqual(mockData);
  });

  test('fetchIngredients.rejected — должен установить loading=false и установить ошибку', () => {
    const stateWithRequest = {
      ...initialState,
      loading: true
    };

    const newState = ingredientsReducer(
      stateWithRequest,
      fetchIngredients.rejected(mockError, '')
    );

    expect(newState.loading).toBe(false);
    expect(newState.error).toEqual(mockError.message);
    expect(newState.data).toEqual([]);
  });
});
